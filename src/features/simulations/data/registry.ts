const groupCache: Partial<Record<SimulationGroup, SimulationDefinition[]>> = {};

export async function loadSimulationsByGroup(group: SimulationGroup): Promise<SimulationDefinition[]> {
  if (groupCache[group]) {
    return groupCache[group]!;
  }
  let items: SimulationDefinition[] = [];
  if (group === 'grade10') {
    const mod = await import('./grade10Data');
    items = mod.GRADE_10_SIMULATIONS;
  } else if (group === 'grade11') {
    const [a, b] = await Promise.all([import('./grade11PartA'), import('./grade11PartB')]);
    items = [...a.GRADE_11_PART_A, ...b.GRADE_11_PART_B];
  } else if (group === 'grade12') {
    const [a, b] = await Promise.all([import('./grade12PartA'), import('./grade12PartB')]);
    items = [...a.GRADE_12_PART_A, ...b.GRADE_12_PART_B];
  } else {
    const [a, b] = await Promise.all([import('./skillsPartA'), import('./skillsPartB')]);
    items = [...a.SKILLS_PART_A, ...b.SKILLS_PART_B];
  }
  groupCache[group] = items;
  return items;
}

export async function loadSimulationById(simId: string): Promise<SimulationDefinition | undefined> {
  const meta = SIMULATION_CATALOG.find((item) => item.id === simId);
  if (!meta) return undefined;
  const list = await loadSimulationsByGroup(meta.group);
  return list.find((item) => item.id === simId);
}

export async function loadAllSimulations(): Promise<SimulationDefinition[]> {
  const [g10, g11, g12, sk] = await Promise.all([
    loadSimulationsByGroup('grade10'),
    loadSimulationsByGroup('grade11'),
    loadSimulationsByGroup('grade12'),
    loadSimulationsByGroup('skills'),
  ]);
  return [...g10, ...g11, ...g12, ...sk];
}
